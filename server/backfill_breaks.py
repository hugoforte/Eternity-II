# The published schedules cap the total breaks a board can ever carry (see
# ScanSolver.SCHEDULE_BLACKWOOD / SCHEDULE_VERHAARD); a computed value outside
# this range means something about the row doesn't match our assumptions, and
# it is safer to leave it NULL than to write a guess.
MAX_PLAUSIBLE_BREAKS = 12


def recover_breaks(config, best_depth, matched_edges):
    """Return the breaks count for one row, or None if it can't be recovered."""
    engine = (config or {}).get("engine")
    if engine != "scan":
        # MrvSolver never slips; neither did the single-solver app this
        # project started as, before "engine" existed as a concept at all.
        # This needs no edge count, so it must come before the check below:
        # the oldest attempts have none, and are exactly the ones that were
        # never able to slip.
        return 0
    if matched_edges is None or best_depth is None or best_depth <= 0:
        return None
    fill_order = (config or {}).get("fillOrder", "banded")
    table = CHECKS_BEFORE.get(fill_order)
    if table is None or best_depth >= len(table):
        return None
    breaks = table[best_depth] - matched_edges
    if breaks < 0 or breaks > MAX_PLAUSIBLE_BREAKS:
        return None
    return breaks


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DB
    if not os.path.isfile(path):
        print("no database at %s" % path)
        return 1

    conn = sqlite3.connect(path, timeout=30)
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        "SELECT id, best_depth, matched_edges, config_json FROM attempts "
        "WHERE breaks IS NULL").fetchall()

    updates = []
    unrecoverable = 0
    for r in rows:
        try:
            cfg = json.loads(r["config_json"]) if r["config_json"] else {}
        except (TypeError, ValueError):
            cfg = {}
        breaks = recover_breaks(cfg, r["best_depth"], r["matched_edges"])
        if breaks is None:
            unrecoverable += 1
            continue
        updates.append((breaks, r["id"]))

    conn.executemany("UPDATE attempts SET breaks=? WHERE id=?", updates)
    conn.commit()

    clean = sum(1 for b, _ in updates if b == 0)
    print("rows examined      : %d" % len(rows))
    print("breaks recovered   : %d (%d of them clean, 0 breaks)" % (len(updates), clean))
    print("left NULL          : %d (no matched-edge count, or outside the plausible range)"
          % unrecoverable)

    best_row = conn.execute(
        "SELECT id, best_depth FROM attempts WHERE status != 'running' "
        "AND nodes > 0 AND breaks = 0 ORDER BY best_depth DESC, id ASC LIMIT 1").fetchone()
    if best_row:
        print("clean pieces record after recovery: %d (attempt #%d)"
              % (best_row["best_depth"], best_row["id"]))
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
