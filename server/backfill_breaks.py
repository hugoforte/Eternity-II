"""One-time recovery of ``breaks`` for attempts recorded before it was tracked.

``breaks`` (attempts.py / db.py) was added partway through this app's life, so
every attempt finished before that column existed has ``breaks = NULL`` even
though the value was fully determined at the time. It can be reconstructed
exactly, with no re-running of the search, because:

    matched_edges = checksBefore[fillOrder][bestDepth] - breaks

``checksBefore[depth]`` is how many of the board's internal edges the first
``depth`` placements have joined up under a given fill order -- a fixed
property of the order alone (see ScanSolver.java's own field of the same
name), not of the search, the seed, or the piece colours. The two arrays
below were generated once from the real `FillOrder.bandedScan(16)` /
`FillOrder.rowMajor(16)`, using the exact formula ScanSolver builds
`checksBefore` with; regenerate them (see the comment above each) if
`FillOrder.java`'s orders ever change.

An `MrvSolver` attempt (or one from before `engine` existed at all, i.e. the
single-solver app this project started as) never slips, so its breaks is
trivially 0 regardless of depth.

Run with:  python3 server/backfill_breaks.py [path/to/eternity2.sqlite]
Back up the database first -- this writes to it. Safe to re-run: it only ever
touches rows where breaks is still NULL.
"""

